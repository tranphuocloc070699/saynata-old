-- TASK-93.3: one /api/sync call for History and Liked, and settings that follow the account.
-- change_seq comes from one sequence; the client's cursor is the biggest change_seq it has seen.
CREATE SEQUENCE sync_change_seq START WITH 2 INCREMENT BY 1;

-- History per account. A removed item stays as a tombstone (deleted = true) so other devices delete it too.
-- text_key is the SavedItem.key rule (word: lowercase, one space; sentence: trimmed). at is the client time (last-write-wins).
CREATE TABLE history_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind       VARCHAR(10)              NOT NULL,
    text_key   VARCHAR(500)             NOT NULL,
    text       VARCHAR(500)             NOT NULL,
    preview    VARCHAR(300)             NOT NULL,
    chip       VARCHAR(40),
    at         TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted    BOOLEAN                  NOT NULL DEFAULT FALSE,
    change_seq BIGINT                   NOT NULL,
    CONSTRAINT uq_history_item_key UNIQUE (user_id, kind, text_key)
);
CREATE INDEX idx_history_item_user_seq ON history_item (user_id, change_seq);

-- Liked items get tombstones, a client time and a cursor too. Old rows: at = created_at.
ALTER TABLE liked_item ADD COLUMN chip VARCHAR(40);
ALTER TABLE liked_item ADD COLUMN at TIMESTAMP WITH TIME ZONE;
ALTER TABLE liked_item ADD COLUMN deleted BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE liked_item ADD COLUMN change_seq BIGINT;
UPDATE liked_item SET at = created_at;
-- Old rows get 1: a first sync (since 0) returns them, and every later change has a bigger number.
UPDATE liked_item SET change_seq = 1;
ALTER TABLE liked_item ALTER COLUMN at SET NOT NULL;
ALTER TABLE liked_item ALTER COLUMN change_seq SET NOT NULL;
CREATE INDEX idx_liked_item_user_seq ON liked_item (user_id, change_seq);

-- Settings of the account. history_cleared_at: a "clear all" at that client time; an older add is ignored.
CREATE TABLE user_settings (
    user_id            BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    target_language    VARCHAR(20) NOT NULL DEFAULT 'vi',
    show_translation   VARCHAR(20) NOT NULL DEFAULT 'remember',
    sync_history       BOOLEAN     NOT NULL DEFAULT TRUE,
    history_cleared_at TIMESTAMP WITH TIME ZONE
);
