-- TASK-118: word forms of backend words ("contaminated" -> "contaminate"), so GET /api/words/{word} answers a form
-- from its lemma's entry instead of asking Claude for a new one. dictionary_form keeps the forms of bundled words.
-- Filled from exports/word-forms/word_forms.tsv (lemminflect, no LLM); see doc-5 "Import word forms (TASK-118)" for the command.
-- No foreign key: the lemma is matched by text with word_lookup.word, and a row whose lemma has no entry is harmless.
CREATE TABLE word_form (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form       VARCHAR(100) NOT NULL,                     -- lower case, for example contaminated or gave up
    lemma      VARCHAR(100) NOT NULL,                     -- lower case, for example contaminate or give up
    form_type  VARCHAR(32)  NOT NULL,                     -- past tense, plural, ... or form
    kind       VARCHAR(10)  NOT NULL DEFAULT 'word' CHECK (kind IN ('word', 'phrase')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_word_form UNIQUE (form, lemma)
);

CREATE INDEX idx_word_form_form ON word_form (form);
