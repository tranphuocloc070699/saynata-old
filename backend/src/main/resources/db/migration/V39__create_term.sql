-- TASK-119.1: terms, named things from any field (Node.js, Nuxt, Stoicism), so GET /api/words/{word} can show a short
-- simple definition and the official site below the English senses ("swift" = fast, plus Swift the language), or alone
-- for a text that is not an English word ("nuxtjs"). Filled offline from Wikidata (exports/terms, TASK-119.2).
CREATE TABLE term (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wikidata_id       VARCHAR(16)   NOT NULL,                -- Q-id, for example Q756100 (Node.js)
    name              VARCHAR(200)  NOT NULL,                -- as written, for example Node.js
    field             VARCHAR(250),                          -- Wikidata description, for example JavaScript runtime
    simple_definition VARCHAR(500),                          -- one simple sentence; null until written (TASK-119.4)
    official_url      VARCHAR(500),                          -- Wikidata P856, never written by an LLM
    wikipedia_url     VARCHAR(500),
    popularity        INTEGER       NOT NULL DEFAULT 0,      -- Wikidata sitelink count, most popular first
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_term_wikidata UNIQUE (wikidata_id)
);

-- One row per way to write a term. alias_key is TermKeys.key: lower case without dots, dashes, underscores, apostrophes
-- and spaces, so Nuxt.js, NuxtJS and nuxt js are one key (nuxtjs).
CREATE TABLE term_alias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias_key  VARCHAR(100) NOT NULL,
    term_id    BIGINT       NOT NULL REFERENCES term (id) ON DELETE CASCADE,
    source     VARCHAR(16)  NOT NULL DEFAULT 'wikidata' CHECK (source IN ('wikidata', 'rule', 'llm', 'manual')),
    CONSTRAINT uq_term_alias UNIQUE (alias_key, term_id)
);

CREATE INDEX idx_term_alias_key ON term_alias (alias_key);
