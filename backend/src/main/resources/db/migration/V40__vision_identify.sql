-- TASK-121.1: what Gemini said about one photo (POST /api/vision/identify). The key is the SHA-256 of the image bytes
-- plus the vision prompt version, so the same photo is paid once. The photo itself is NEVER stored, only its hash.
-- The labels in this table are also the ones GET /api/words/{label} may describe (VisionLabels).
CREATE TABLE vision_identify (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_hash     VARCHAR(64)  NOT NULL,                   -- sha256 hex of the image bytes
    prompt_version VARCHAR(20)  NOT NULL,                   -- app.claude.vision-prompt-version
    label          VARCHAR(100) NOT NULL,                   -- lower case, for example "teapot" or "phở"
    kind           VARCHAR(10)  NOT NULL CHECK (kind IN ('object', 'dish', 'text')),
    confidence     DOUBLE PRECISION NOT NULL,               -- 0..1, the model's own answer
    model          VARCHAR(80)  NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_vision_identify UNIQUE (image_hash, prompt_version)
);

CREATE INDEX idx_vision_identify_label ON vision_identify (label, prompt_version);
